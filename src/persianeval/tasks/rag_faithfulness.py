"""RAG faithfulness task: is the proposed answer grounded in the passage?"""

from __future__ import annotations

from persianeval.tasks.base import AbstractTask, ScoringKind, ScoringSpec


class RagFaithfulnessTask(AbstractTask):
    """Judge whether a proposed answer is faithful to the given passage.

    Passages are synthetic documents with concrete entities and numbers;
    unfaithful answers mutate an entity, a number, or assert something the
    passage never says. This is the direct evaluation companion for
    Persian RAG pipelines (e.g. the docubot project).
    """

    name = "rag_faithfulness"
    title_en = "RAG Faithfulness (FA)"
    title_fa = "وفاداری به متن (RAG)"
    description_en = (
        "Given a Persian passage, a question and a proposed answer, decide "
        "whether the answer is fully grounded in the passage (بله/خیر)."
    )
    description_fa = (
        "با داشتن متن، پرسش و پاسخ پیشنهادی، مشخص کن پاسخ کاملاً به متن وفادار است یا نه (بله/خیر)."
    )
    data_file = "rag_faithfulness.jsonl"
    min_samples = 200
    system_prompt = "فقط «بله» یا «خیر» بنویس؛ هیچ توضیح اضافه‌ای ننویس."
    scoring = ScoringSpec(kind=ScoringKind.EXACT)
    source = (
        "50 synthetic grounded passages x 4 answer variants (2 faithful, 2 "
        "unfaithful) generated by scripts/generate_data/gen_rag.py; labels in "
        "metadata. Apache-2.0."
    )
