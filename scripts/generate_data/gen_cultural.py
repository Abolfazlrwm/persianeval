def main() -> None:
    """Generate exactly 200 cultural knowledge samples with options embedded."""
    rows: list[dict[str, Any]] = []
    for question, options, correct_index, category in ITEMS:
        rendered = "\n".join(f"{LETTERS[i]}) {option}" for i, option in enumerate(options))
        rows.append(
            {
                "id": f"cultural_knowledge-{len(rows) + 1:04d}",
                "prompt": f"{question}\n{rendered}\nفقط حرف گزینهٔ درست را بنویس.",
                "expected": LETTERS[correct_index],
                "metadata": {"category": category, "options": options, "answer_text": options[correct_index]},
            }
        )
    assert len(rows) == 200, f"expected 200 rows, got {len(rows)}"
    assert len({row["id"] for row in rows}) == 200, "ids must be unique"
    assert len({row["prompt"] for row in rows}) == 200, "prompts must be unique"
    write_jsonl("cultural_knowledge", rows)


if __name__ == "__main__":
    main()
