def main() -> None:
    """Generate exactly 200 reading comprehension samples."""
    rows: list[dict[str, Any]] = []
    for passage_index, (passage, questions) in enumerate(PASSAGES, start=1):
        for question_number, (question, expected) in enumerate(questions, start=1):
            rows.append(
                {
                    "id": f"reading_comprehension-{passage_index * 10 + question_number:04d}",
                    "prompt": f"متن:\n{passage}\n\nپرسش: {question}\nفقط پاسخ کوتاه را بنویس.",
                    "expected": expected,
                    "metadata": {"passage_id": passage_index, "question_number": question_number},
                }
            )
    assert len(rows) == 200, f"expected 200 rows, got {len(rows)}"
    assert len({row["id"] for row in rows}) == 200, "ids must be unique"
    write_jsonl("reading_comprehension", rows)


if __name__ == "__main__":
    main()
