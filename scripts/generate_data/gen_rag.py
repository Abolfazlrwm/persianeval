_ERROR_TYPES = {"wrong_entity": "جابه‌جایی شخصیت/مکان", "wrong_number": "عدد اشتباه"}


def main() -> None:
    """Generate exactly 200 RAG faithfulness samples (50/50 faithful/unfaithful)."""
    rows: list[dict[str, Any]] = []
    for passage_index, (passage, pairs) in enumerate(PASSAGES, start=1):
        for _question_number, (question, faithful, unfaithful, error_type) in enumerate(pairs, start=1):
            # Every (question, pair) is presented twice: once with the faithful
            # answer and once with the unfaithful variant -> 50/50 label split.
            variants: list[tuple[str, str, str | None]] = [
                (faithful, "faithful", None),
                (unfaithful, "unfaithful", _ERROR_TYPES[error_type]),
            ]
            for answer, label, error_label in variants:
                rows.append(
                    {
                        "id": f"rag_faithfulness-{len(rows) + 1:04d}",
                        "prompt": (
                            f"متن:\n{passage}\n\nپرسش: {question}\nپاسخ پیشنهادی: {answer}\n\n"
                            "آیا پاسخ پیشنهادی کاملاً با متن سازگار است؟ فقط «بله» یا «خیر» بنویس."
                        ),
                        "expected": "بله" if label == "faithful" else "خیر",
                        "metadata": {
                            "passage_id": passage_index,
                            "label": label,
                            "error_type": error_label,
                            "proposed_answer": answer,
                        },
                    }
                )
    assert len(rows) == 200, f"expected 200 rows, got {len(rows)}"
    assert len({row["id"] for row in rows}) == 200, "ids must be unique"
    assert len({row["prompt"] for row in rows}) == 200, "prompts must be unique"
    labels = [row["metadata"]["label"] for row in rows]
    assert labels.count("faithful") == 100, "label split must be exactly 100/100"
    assert labels.count("unfaithful") == 100, "label split must be exactly 100/100"
    write_jsonl("rag_faithfulness", rows)


if __name__ == "__main__":
    main()
