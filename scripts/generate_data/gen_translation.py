def main() -> None:
    """Generate exactly 200 translation samples."""
    rows: list[dict[str, Any]] = []
    for register, direction, source_text, reference in PAIRS:
        if direction == "fa2en":
            prompt = f"این جمله را به انگلیسی ترجمه کن:\n«{source_text}»"
        else:
            prompt = f'این جمله را به فارسی ترجمه کن:\n"{source_text}"'
        rows.append(
            {
                "id": f"translation_fa_en-{len(rows) + 1:04d}",
                "prompt": prompt,
                "expected": reference,
                "metadata": {"register": register, "direction": direction, "source": source_text},
            }
        )
    assert len(rows) == 200, f"expected 200 rows, got {len(rows)}"
    assert len({row["id"] for row in rows}) == 200, "ids must be unique"
    write_jsonl("translation_fa_en", rows)


if __name__ == "__main__":
    main()
